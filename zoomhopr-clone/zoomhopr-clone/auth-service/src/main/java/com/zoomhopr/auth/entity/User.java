package com.zoomhopr.auth.entity;

import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.time.Instant;

@Entity
@Table(name = "users", uniqueConstraints = @UniqueConstraint(columnNames = "email"))
@Getter
@Setter
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class User {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private String id;

    @Column(nullable = false)
    private String fullName;

    @Column(nullable = false, unique = true)
    private String email;

    @Column(nullable = false)
    private String phone;

    @Column(nullable = false)
    private String passwordHash;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private Role role; // RIDER, DRIVER, HOST, ADMIN

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private KycStatus kycStatus; // PENDING, VERIFIED, REJECTED

    @Column(nullable = false, updatable = false)
    private Instant createdAt;

    @PrePersist
    void onCreate() {
        this.createdAt = Instant.now();
        if (this.kycStatus == null) this.kycStatus = KycStatus.PENDING;
    }

    public enum Role { RIDER, DRIVER, HOST, ADMIN }
    public enum KycStatus { PENDING, VERIFIED, REJECTED }
}
